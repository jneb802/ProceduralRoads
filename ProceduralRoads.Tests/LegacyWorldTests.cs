using System;
using System.Collections.Generic;
using System.Linq;
using System.Reflection;
using UnityEngine;
using Valheim.Testing;
using Valheim.Testing.Doubles;
using Xunit;

namespace ProceduralRoads.Tests;

/// <summary>
/// A world saved by ProceduralRoads 1.4.4, opened by this build. The hard rule: a road network saved by a released
/// version is never regenerated or rewritten, and new behaviour reaches only zones nobody has generated yet. Every
/// automatic writer is run over a zone the 1.4.4 world had already generated, and the zone must come out byte for byte
/// as it went in. A zone generated after the upgrade gets the new road.
/// </summary>
public sealed class LegacyWorldTests : IDisposable
{
    private sealed class FlatWorld : WorldGenerator
    {
        public override float GetHeight(float x, float z) => 40f;
        public override void GetRiverWeight(float x, float z, out float weight, out float width) { weight = 0; width = 0; }
    }

    private static readonly int GlobalDataHash = "ProceduralRoads_GlobalData".GetStableHashCode();

    /// <summary>Generated by 1.4.4 with its network: its compiler holds that build's road and a player's dig.</summary>
    internal static readonly Vector2s OldZone = new(0, 0);
    /// <summary>Generated by 1.4.4 in a later session: no road (1.4.4 only wrote roads in the session that generated
    /// the network), no terrain compiler, possibly a player's base on the road line.</summary>
    internal static readonly Vector2s LaterZone = new(1, 0);
    /// <summary>Never generated.</summary>
    internal static readonly Vector2s NewZone = new(-1, 0);

    private readonly ValheimWorldScope _world = new ValheimWorldScope().WithWorld(new FlatWorld()).WithZdos().WithZoneSystem().WithScene().AsServer();
    internal byte[] Blob = Array.Empty<byte>();

    public LegacyWorldTests()
    {
        SetWorldDataLoaded(false);
        RoadNetworkPersistence.Reset(); RoadSpatialGrid.Clear(); RoadNetworkGenerator.Reset(); RoadTerrainModifier.ResetForWorld();
        NetworkCutoff.Forget();
        RoadNetworkGenerator.RoadWidth = 4;
    }

    public void Dispose()
    {
        SetWorldDataLoaded(false);
        NetworkCutoff.Forget();
        RoadNetworkPersistence.Reset(); RoadSpatialGrid.Clear(); RoadNetworkGenerator.Reset(); RoadTerrainModifier.ResetForWorld();
        _world.Dispose();
    }

    internal static void SetWorldDataLoaded(bool value) =>
        typeof(RoadLifecycleManager).GetField("m_worldDataLoaded", BindingFlags.NonPublic | BindingFlags.Static)!.SetValue(null, value);

    internal static ZDO Metadata()
    {
        var found = new List<ZDO>(); int index = 0;
        while (!ZDOMan.instance.GetAllZDOsWithPrefabIterative(RoadNetworkPersistence.MetadataPrefabName, found, ref index)) { }
        return found.Single();
    }

    /// <summary>
    /// The 1.4.4 save: a road east-west along z = 4 through all three zones, saved in 1.4.4's format on the metadata
    /// object, and the zones the save says were generated. Nothing of this build's is in memory afterwards.
    /// </summary>
    private void SaveAsReleased144()
    {
        var path = new List<Vector2>();
        for (float x = -150f; x <= 150f; x += 8f) path.Add(new Vector2(x, 4f));
        RoadSpatialGrid.AddRoadPath(path, 4f, WorldGenerator.instance);
        RoadSpatialGrid.FinalizeRoadNetwork();
        Blob = Released144.BlobOfCurrentGrid();
        RoadNetworkPersistence.EnsureMetadataInstance();
        Metadata().Set(GlobalDataHash, Blob);
        RoadNetworkPersistence.Reset(); RoadSpatialGrid.Clear(); RoadNetworkGenerator.Reset();
        ZoneSystem.instance!.Generated.Add(OldZone);
        ZoneSystem.instance.Generated.Add(LaterZone);
    }

    /// <summary>The upgraded build opens the world: locations in place, then ZNet's world load returns.</summary>
    internal static void OpenWorld()
    {
        var zones = ZoneSystem.instance!;
        if (zones.m_locationInstances.Count == 0)
            TestLocations.Add(zones, new ZoneSystem.LocationInstance
            {
                m_position = new Vector3(0f, 0f, 600f),
                m_location = new ZoneSystem.ZoneLocation { m_prefab = new SoftReferenceableAssets.SoftReference<GameObject>("StartTemple"), m_exteriorRadius = 16f },
            });
        zones.LoadLocationsGeneratedFromSave(true);
        RoadLifecycleManager.OnZoneSystemStart(zones);
        RoadLifecycleManager.OnWorldDataLoaded();
    }

    /// <summary>A player's terrain in the old zone: 1.4.4's road deltas and paved paint, plus a dig in the footprint.</summary>
    private static void PlayerTerrain(TerrainComp compiler)
    {
        for (int i = 0; i < compiler.m_levelDelta.Length; i++)
        {
            compiler.m_levelDelta[i] = (i % 7) * 0.05f;
            compiler.m_modifiedHeight[i] = i % 3 == 0;
            compiler.m_paintMask[i] = new Color(0.2f, 0.4f, 0.6f, 0.8f);
            compiler.m_modifiedPaint[i] = i % 5 == 0;
        }
        int dig = (compiler.m_width / 2 + 2) * (compiler.m_width + 1) + compiler.m_width / 2; // near the road, z = 4
        compiler.m_levelDelta[dig] = -1.5f;
        compiler.m_modifiedHeight[dig] = true;
        compiler.Save();
    }


    [Fact]
    public void AZoneGeneratedAfterTheUpgradeGetsTheNewRoad()
    {
        SaveAsReleased144();
        OpenWorld();
        Assert.True(RoadNetworkGenerator.RoadsLoadedFromZDO);
        Assert.False(NetworkCutoff.Excludes(NewZone));

        // Generated now, in Full mode: the game adds it to the generated set, makes its heightmap, then SpawnZone's postfix runs.
        ZoneSystem.instance!.Generated.Add(NewZone);
        var fresh = _world.RegisterHeightmap(NewZone, withCompiler: false);
        RoadTerrainModifier.OnZoneSpawned(NewZone, RoadSpatialGrid.GetRoadPointsInZone(NewZone));
        Assert.NotNull(fresh.m_terrainComp);
        Assert.True(RoadTerrainModifier.CarriesCurrentRoads(fresh.m_terrainComp!), "the new zone must carry the road");

        // The next session: the new zone stays the network's, the old ones stay excluded.
        RoadLifecycleManager.OnPrepareSave();
        Assert.Equal(Blob, Metadata().GetByteArray(GlobalDataHash));
        RoadLifecycleManager.OnZoneSystemDestroy(ZoneSystem.instance);
        RoadNetworkPersistence.Reset(); RoadSpatialGrid.Clear();
        OpenWorld();
        Assert.True(RoadNetworkGenerator.RoadsLoadedFromZDO);
        Assert.False(NetworkCutoff.Excludes(NewZone), "a zone generated with the network keeps it");
        Assert.True(NetworkCutoff.Excludes(OldZone));
        Assert.True(NetworkCutoff.Excludes(LaterZone));
    }

}
